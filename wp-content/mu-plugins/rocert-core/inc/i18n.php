function rocert_lang(): string
{
    if (function_exists('pll_current_language')) {
        $lang = pll_current_language('slug');
        if ($lang) {
            return $lang;
        }
    }
    return str_starts_with(get_locale(), 'en') ? 'en' : 'ro';
}

